op_1=int(input("Введіть величину першого опору в Ом: "))
op_2=int(input("Введіть величину другого опору в Ом: "))
typ=int(input("Введіть тип з'єднання (1 - послідовний, 2 - паралельний): "))
if typ==1:
    op_kola=op_1+op_2
    print(f"Опір електричного кола = {op_kola}")
elif typ==2:
    op_kola=(op_1+op_2)/(op_1*op_2)
    print(f"Опір електричного кола = {op_kola}")
else:
    print("Вводьте правильний тип з'єднання")
